#!/usr/bin/env node

import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import process from 'node:process';
import { fileURLToPath } from 'node:url';

import { auditPackageManager, satisfiesEnginesRange } from './audit-package-manager.mjs';

const scriptDirectory = path.dirname(fileURLToPath(import.meta.url));
const repositoryRoot = path.resolve(scriptDirectory, '..');
const auditScript = path.join(scriptDirectory, 'audit-package-manager.mjs');

const VALID_FILES = {
  '.nvmrc': '24.19.0\n',
  '.yarnrc.yml': 'enableGlobalCache: true\n\nnodeLinker: node-modules\n',
  'package.json': `${JSON.stringify(
    { name: 'fixture', packageManager: 'yarn@4.17.0', engines: { node: '>=24 <25' } },
    null,
    2
  )}\n`,
  'yarn.lock':
    '# This file is generated by running "yarn install" inside your project.\n\n__metadata:\n  version: 10\n  cacheKey: 10\n',
  '.github/workflows/ci.yml':
    'jobs:\n  verify:\n    steps:\n      - uses: actions/setup-node@49933ea5288caeca8642d1e84afbd3f7d6820020 # v4\n        with:\n          node-version: 24.19.0\n',
  '.github/workflows/branch-flow.yml':
    'jobs:\n  validate:\n    steps:\n      - uses: actions/setup-node@49933ea5288caeca8642d1e84afbd3f7d6820020 # v4\n        with:\n          node-version-file: .nvmrc\n',
};

let passed = 0;
let fixtureNumber = 0;

async function createFixture(tempRoot, label, mutate) {
  fixtureNumber += 1;
  const rootDir = path.join(
    tempRoot,
    `${String(fixtureNumber).padStart(2, '0')}-${label.replace(/[^a-z0-9]+/giu, '-')}`
  );
  const files = { ...VALID_FILES };
  mutate?.(files);
  for (const [name, content] of Object.entries(files)) {
    if (content === null) continue;
    const destination = path.join(rootDir, ...name.split('/'));
    await fs.mkdir(path.dirname(destination), { recursive: true });
    await fs.writeFile(destination, content);
  }
  return rootDir;
}

async function expectPass(tempRoot, label, mutate) {
  const rootDir = await createFixture(tempRoot, label, mutate);
  await auditPackageManager({ rootDir });
  passed += 1;
  return rootDir;
}

async function expectFailure(tempRoot, label, mutate, expected) {
  const rootDir = await createFixture(tempRoot, label, mutate);
  await assert.rejects(auditPackageManager({ rootDir }), expected, label);
  passed += 1;
}

function editPackageJson(files, edit) {
  const packageJson = JSON.parse(files['package.json']);
  edit(packageJson);
  files['package.json'] = `${JSON.stringify(packageJson, null, 2)}\n`;
}

const tempRoot = await fs.mkdtemp(path.join(os.tmpdir(), 'fearless-package-manager-audit-'));
try {
  await auditPackageManager({ rootDir: repositoryRoot });
  passed += 1;

  const clean = await expectPass(tempRoot, 'clean');
  const cli = spawnSync(process.execPath, [auditScript, '--root', clean], { encoding: 'utf8' });
  assert.equal(cli.status, 0, cli.stderr);
  assert.match(cli.stdout, /Package manager audit passed: yarn@4\.17\.0; Node 24\.19\.0/u);
  passed += 1;

  for (const lockfile of ['pnpm-lock.yaml', 'pnpm-workspace.yaml', 'package-lock.json', 'npm-shrinkwrap.json']) {
    await expectFailure(
      tempRoot,
      `stray-${lockfile}`,
      (files) => (files[lockfile] = 'lockfileVersion: 9.0\n'),
      new RegExp(`${lockfile.replaceAll('.', '\\.')} must not exist`, 'u')
    );
  }

  const failingCli = spawnSync(
    process.execPath,
    [auditScript, '--root', await createFixture(tempRoot, 'cli-stray-pnpm', (files) => (files['pnpm-lock.yaml'] = ''))],
    { encoding: 'utf8' }
  );
  assert.equal(failingCli.status, 1);
  assert.match(failingCli.stderr, /Package manager audit failed: pnpm-lock\.yaml must not exist/u);
  passed += 1;

  await expectFailure(
    tempRoot,
    'unpinned-package-manager',
    (files) => editPackageJson(files, (packageJson) => (packageJson.packageManager = 'yarn@4.10.3')),
    /packageManager must be yarn@4\.17\.0/u
  );
  await expectFailure(
    tempRoot,
    'pnpm-package-manager',
    (files) => editPackageJson(files, (packageJson) => (packageJson.packageManager = 'pnpm@10.0.0')),
    /packageManager must be yarn@4\.17\.0/u
  );
  await expectFailure(
    tempRoot,
    'nvmrc-differs-from-ci',
    (files) => (files['.nvmrc'] = '24.18.0\n'),
    /node-version "24\.19\.0" does not match \.nvmrc 24\.18\.0/u
  );
  await expectFailure(
    tempRoot,
    'nvmrc-outside-engines',
    (files) => {
      files['.nvmrc'] = '26.11.0\n';
      files['.github/workflows/ci.yml'] = files['.github/workflows/ci.yml'].replace('24.19.0', '26.11.0');
    },
    /\.nvmrc 26\.11\.0 does not satisfy package\.json engines\.node/u
  );
  await expectFailure(
    tempRoot,
    'partial-nvmrc',
    (files) => (files['.nvmrc'] = '24\n'),
    /\.nvmrc must be an exact x\.y\.z Node version/u
  );
  await expectFailure(
    tempRoot,
    'foreign-node-version-file',
    (files) =>
      (files['.github/workflows/branch-flow.yml'] = files['.github/workflows/branch-flow.yml'].replace(
        'node-version-file: .nvmrc',
        'node-version-file: package.json'
      )),
    /node-version-file must be \.nvmrc/u
  );
  await expectFailure(
    tempRoot,
    'ci-without-node-pin',
    (files) => (files['.github/workflows/ci.yml'] = 'jobs:\n  verify:\n    steps:\n      - run: node --version\n'),
    /ci\.yml must pin Node/u
  );
  await expectFailure(
    tempRoot,
    'unsupported-engines-syntax',
    (files) => editPackageJson(files, (packageJson) => (packageJson.engines.node = '^24 || ^26')),
    /unsupported engines\.node range syntax/u
  );
  await expectFailure(
    tempRoot,
    'dead-scoped-registry',
    (files) =>
      (files['.yarnrc.yml'] +=
        'npmScopes:\n  soramitsu:\n    npmRegistryServer: "https://nexus.iroha.tech/repository/npm-group/"\n'),
    /names unreviewed registry "https:\/\/nexus\.iroha\.tech\/repository\/npm-group"/u
  );
  await expectPass(tempRoot, 'public-registry', (files) => {
    files['.yarnrc.yml'] += 'npmRegistryServer: "https://registry.yarnpkg.com/" # default\n';
  });
  await expectFailure(
    tempRoot,
    'wildcard-git-approval',
    (files) => (files['.yarnrc.yml'] = `approvedGitRepositories:\n  - "**"\n\n${files['.yarnrc.yml']}`),
    /approves every Git repository/u
  );
  await expectFailure(
    tempRoot,
    'inline-wildcard-git-approval',
    (files) => (files['.yarnrc.yml'] = `approvedGitRepositories: ["**"]\n${files['.yarnrc.yml']}`),
    /approves every Git repository/u
  );
  await expectPass(tempRoot, 'explicit-git-approval', (files) => {
    files['.yarnrc.yml'] = `approvedGitRepositories:\n  - "https://github.com/soramitsu/**"\n${files['.yarnrc.yml']}`;
  });
  await expectFailure(
    tempRoot,
    'yarn-classic-lockfile',
    (files) => (files['yarn.lock'] = '# yarn lockfile v1\n\n"bn.js@^5.2.1":\n  version "5.2.3"\n'),
    /yarn\.lock lacks the Yarn Berry __metadata header/u
  );
  await expectFailure(tempRoot, 'missing-yarn-lock', (files) => (files['yarn.lock'] = null), /cannot read yarn\.lock/u);

  for (const [version, range, expected] of [
    ['24.19.0', '>=24 <25', true],
    ['24.0.0', '>=24 <25', true],
    ['25.0.0', '>=24 <25', false],
    ['23.11.1', '>=24 <25', false],
    ['24.19.0', '<=24', true],
    ['25.0.0', '<=24', false],
    ['24.19.0', '>24', false],
    ['25.0.0', '>24', true],
    ['24.19.0', '24', true],
    ['24.19.0', '24.19', true],
    ['24.20.0', '24.19', false],
    ['24.19.0', '=24.19.0', true],
    ['24.19.1', '24.19.0', false],
  ]) {
    assert.equal(satisfiesEnginesRange(version, range), expected, `${version} against ${range}`);
    passed += 1;
  }

  console.log(`Package manager audit self-test passed (${passed} checks).`);
} finally {
  await fs.rm(tempRoot, { force: true, recursive: true });
}
